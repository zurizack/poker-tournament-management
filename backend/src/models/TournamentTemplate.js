import mongoose from "mongoose";
import { levelSchema } from "./levelSchema.js";

// A manager's saved tournament blueprint. Deliberately excludes
// players/clock/status — those only exist on a live ActiveTournament.
// Mirrors the rebuy/add-on fields on ActiveTournament so a template can
// fully seed a launch without the manager re-entering those rules.
const templateSchema = new mongoose.Schema(
  {
    ownerUsername: { type: String, required: true, index: true },
    name: { type: String, required: true, trim: true },
    levels: { type: [levelSchema], required: true },
    startingStack: { type: Number, required: true },
    allowRebuys: { type: Boolean, default: true },
    rebuyLimitType: { type: String, enum: ["unlimited", "limited"], default: "unlimited" },
    maxRebuysPerPlayer: { type: Number, default: null },
    allowAddOn: { type: Boolean, default: true },
    // Distinguishes a template the manager deliberately saved from one
    // auto-generated by "Launch Tournament Now" so the UI can label/filter it.
    source: { type: String, enum: ["manual", "quick_launch"], default: "manual" },
  },
  { timestamps: true },
);

export const TournamentTemplate = mongoose.model("TournamentTemplate", templateSchema);
